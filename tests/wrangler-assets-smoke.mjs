import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { expectedPublicAssets } from './public-assets-allowlist.mjs';

const logPath = process.argv[2];
assert.ok(logPath, 'Indica el log de wrangler deploy --dry-run con WRANGLER_LOG=debug.');
const log = (await readFile(logPath, 'utf8')).replace(/\u001b\[[0-9;]*m/g, '');
assert.match(log, /--dry-run: exiting now\./, 'Wrangler debe terminar en modo dry-run');
const wranglerConfig = await readFile(new URL('../wrangler.toml', import.meta.url), 'utf8');
assert.match(wranglerConfig, /^workers_dev = true\s*$/m, 'La URL principal workers.dev debe permanecer habilitada.');
assert.match(wranglerConfig, /^preview_urls = false\s*$/m, 'Las Version URLs deben permanecer deshabilitadas.');
assert.match(wranglerConfig, /^\[triggers\]\r?\ncrons = \["0 5 \* \* \*"\]$/m, 'El cleanup de invitados debe conservar su Cron diario a las 05:00 UTC.');
assert.match(log, /Total Upload:/, 'Wrangler debe completar el empaquetado');
assert.match(log, /env\.DB\s+\(bikestore-store\)\s+D1 Database/, 'El Worker debe enlazar la D1 esperada.');
assert.match(log, /env\.AUTH_EDGE_REGISTER_LIMITER\s+\(30 requests\/60s\)/, 'Falta el binding edge de registro.');
assert.match(log, /env\.AUTH_EDGE_LOGIN_IP_LIMITER\s+\(30 requests\/60s\)/, 'Falta el binding edge de login por IP.');
assert.match(log, /env\.AUTH_EDGE_LOGIN_PAIR_LIMITER\s+\(10 requests\/60s\)/, 'Falta el binding edge de login por par.');
assert.match(log, /env\.AUTH_EDGE_PASSWORD_RESET_LIMITER\s+\(10 requests\/60s\)/, 'Falta el binding edge de recuperación de contraseña.');
assert.match(log, /env\.GUEST_EDGE_CREATE_LIMITER\s+\(30 requests\/60s\)/, 'Falta el binding edge para crear carritos invitados.');
const start = log.match(/Read (\d+) files from the assets directory[^\n]*\n/);
assert.ok(start, 'Wrangler no informó los archivos del directorio de assets.');
const offset = log.indexOf(start[0]) + start[0].length;
const tail = log.slice(offset);
const end = tail.search(/\n(?:Ignoring asset:|Total Upload:)/);
assert.notEqual(end, -1, 'No se encontró el final del inventario de assets de Wrangler.');
const listed = tail.slice(0, end).split(/\r?\n/).map((line) => line.trim()).filter((line) => /^\/[A-Za-z0-9._/-]+$/.test(line)).map((line) => line.slice(1));
const directories = new Set(listed.filter((candidate) => listed.some((other) => other.startsWith(`${candidate}/`))));
const actualFiles = listed.filter((candidate) => !directories.has(candidate)).sort();
const expectedFiles = [...expectedPublicAssets].sort();
assert.deepEqual(actualFiles, expectedFiles, `Wrangler dry-run asset inventory differs from allowlist\nActual: ${actualFiles.join(', ')}\nExpected: ${expectedFiles.join(', ')}`);
console.log(`PASS Wrangler dry-run allowlist: exact ${actualFiles.length}-file inventory (${start[1]} listed entries including directories)`);
